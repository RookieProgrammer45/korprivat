def deep_merge(base: dict, overlay: dict) -> dict:
    out = deepcopy(base)
    for key, value in overlay.items():
        if isinstance(value, dict) and isinstance(out.get(key), dict):
            out[key] = deep_merge(out[key], value)
        else:
            out[key] = value
    return out


def main() -> None:
    for locale, overlay in OVERLAYS.items():
        path = ROOT / "messages" / f"{locale}.json"
        data = json.loads(path.read_text())
        merged = deep_merge(data, overlay)
        items = FAQ_ITEMS.get(locale)
        if items:
            merged = deep_merge(merged, {"faqPage": {"items": items}})
        nav = NAV_CHROME.get(locale)
        if nav:
            merged = deep_merge(merged, {"common": {"nav": nav}})
        hub = LOCATION_HUB_BODY.get(locale)
        if hub:
            merged = deep_merge(merged, {"locationHub": hub})
        serp = SERP_META.get(locale)
        if serp:
            merged = deep_merge(merged, serp)
        path.write_text(json.dumps(merged, ensure_ascii=False, indent=2) + "\n")
        title = merged["locationHub"]["meta"]["indexTitle"]
        print(f"{locale}: indexTitle={title}")


if __name__ == "__main__":
    main()
